def build_html_report(ds: Dataset, charts: list, advice_text: str | None = None) -> str:
    esc = html.escape
    res = A.full_analysis(ds)
    ins = build_insights(ds)

    parts = [f"<!doctype html><html><head><meta charset='utf-8'><title>JARVIS report: {esc(ds.name)}</title>"
             f"<style>{CSS}</style></head><body><div class='wrap'>",
             "<h1>J.A.R.V.I.S</h1>",
             f"<div class='sub'>BUSINESS REPORT · {esc(ds.name)} · {datetime.now():%d %b %Y %H:%M}</div>"]

    parts.append("<h2>KEY METRICS</h2><div class='kpis'>")
    for k in res["kpis"]:
        parts.append(f"<div class='kpi'><b>{esc(k['display'])}</b><span>{esc(k['label'])}</span></div>")
    parts.append("</div>")

    if advice_text:
        parts.append("<h2>STRATEGIC BRIEFING</h2>")
        parts.append(f"<pre>{esc(advice_text)}</pre>")

    parts.append("<h2>FINDINGS</h2>")
    for i in ins:
        meaning = f"<span class='lay'><u>May mean</u> {esc(i['meaning'])}</span>" if i.get("meaning") else ""
        act = f"<em><u>Next step</u> {esc(i['action'])}</em>" if i.get("action") else ""
        parts.append(f"<div class='ins {i['severity']}'><b>{ICON[i['severity']]} {esc(i['title'])}</b>"
                     f"<span class='lay'><u>Observed</u> {esc(i['detail'])}</span>{meaning}{act}</div>")

    actions = top_actions(ins, 6)
    parts.append("<h2>SUGGESTED NEXT STEPS</h2>")
    if actions:
        parts.append("<ol>" + "".join(f"<li>{esc(a)}</li>" for a in actions) + "</ol>")
    else:
        parts.append("<p>The data does not support a specific action beyond the checks above.</p>")

    if charts:
        parts.append("<h2>VISUALISATIONS</h2>")
        for c in charts:
            parts.append(f"<figure><img alt='{esc(c['title'])}' src='{c['image']}'>"
                         f"<figcaption><b>{esc(c['title'])}</b> {esc(c.get('caption') or '')}</figcaption></figure>")

    parts.append("<h2>DETAILED NUMBERS</h2>")
    parts.append(f"<pre>{esc(business_analysis(ds))}</pre>")
    parts.append("<div class='foot'>Generated by JARVIS. All figures are computed from the uploaded dataset. "
                 "Forecasts are statistical projections, not guarantees.</div></div></body></html>")
    return "".join(parts)


def save_html_report(ds: Dataset, html_text: str):
    path = config.OUTPUT_DIR / f"{ds.name.rsplit('.', 1)[0]}_report.html"
    path.write_text(html_text, encoding="utf-8")
    return path
